/** จำบทพูดที่ใช้แล้วในแต่ละหมวด และเริ่มรอบใหม่เมื่อครบทุกประโยค */
export function addRandomEventDialogue(state, card) {
  if (card.source_type !== 'random_event') return card;
  const category = LINES[card.category] ? card.category : 'daily_life';
  const pool = LINES[category];
  state.turn.eventDialogueHistory ||= {};
  const seen = (state.turn.eventDialogueHistory[category] || []).filter((index) => Number.isInteger(index) && index >= 0 && index < pool.length);
  const fresh = pool.map((_, index) => index).filter((index) => !seen.includes(index));
  const choices = fresh.length ? fresh : pool.map((_, index) => index);
  const pick = choices[hashString(`${state.meta?.runId || ''}|${state.profile?.age}|${card.event_id}|${seen.length}`) % choices.length];
  state.turn.eventDialogueHistory[category] = fresh.length ? [...seen, pick] : [pick];
  return { ...card, eventDialogueTh: pool[pick] };
}
