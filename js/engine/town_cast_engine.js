export const getCast = (id) => TOWN_CAST.find((c) => c.id === id);

export function ensureCastState(state, id) {
  const eq = ensureEquality(state);
  eq.cast ||= {};
  eq.cast[id] ||= { done: [], lastAge: null, rel: 0 };
  return eq.cast[id];
}

export const visibleCast = (state) => TOWN_CAST.filter((c) => Number(state.profile?.age || 0) >= c.minAge);

export function nextChapter(state, id) {
  const c = getCast(id);
  if (!c) return null;
  const cs = ensureCastState(state, id);
  const age = Number(state.profile?.age || 0);
  if (cs.lastAge === age) return null;
  return c.chapters.find((ch) => !cs.done.includes(ch.id) && age >= ch.minAge) || null;
}

export function castChatLine(state, id) {
  const c = getCast(id);
  return c.chat[hashString(`${state.meta?.runId || 'x'}|castchat|${id}|${state.profile?.age}`) % c.chat.length];
}

export function resolveChapter(state, id, optionIndex) {
  const c = getCast(id);
  const ch = nextChapter(state, id);
  if (!c || !ch) return { success: false, message: 'ตอนนี้ยังไม่มีเรื่องใหม่ ลองกลับมาปีหน้านะ' };
  const opt = ch.options[optionIndex];
  if (!opt) return { success: false, message: 'ไม่พบตัวเลือก' };
  const [, resultTh, fx] = opt;
  const cs = ensureCastState(state, id);
  const eq = ensureEquality(state);
  const before = eq.townIndex;
  const age = Number(state.profile?.age || 0);
  eq.townIndex = clamp(eq.townIndex + (fx.idx || 0), 0, 100);
  cs.rel = clamp(cs.rel + (fx.rel || 0), -100, 100);
  if (fx.cash) state.finance.cash = Math.round(Number(state.finance.cash || 0) + fx.cash);
  applyStatEffects(state, fx.effects || {});
  cs.done.push(ch.id); cs.lastAge = age;
  let friend = null;
  if (cs.rel >= CAST_FRIEND_THRESHOLD) {
    friend = addFriendFromEncounter(state, { id: `cast_${id}`, identity: c.identity }, c.name);
    if (friend) { friend.isCast = true; friend.roleTitle = c.role; friend.relationship = clamp(50 + cs.rel, 0, 100); }
  } else {
    const f = (state.relationships?.npcs || []).find((n) => n.id === `friend_cast_${id}`);
    if (f) f.relationship = clamp(50 + cs.rel, 0, 100);
  }
  state.turn?.lifeFeedLog?.push({ age, monthTh: 'ตลอดปี', type: 'cast', title: `${c.name}: ${ch.title}`, message: resultTh });
  return { success: true, message: resultTh, indexBefore: before, indexAfter: eq.townIndex, friend, rel: cs.rel, chaptersDone: cs.done.length, total: c.chapters.length };
}

function findNear(map, tx, ty) {
  for (let r = 0; r < 12; r++) {
    for (let dy = -r; dy <= r; dy++) for (let dx = -r; dx <= r; dx++) {
      if (Math.max(Math.abs(dx), Math.abs(dy)) !== r) continue;
      if (walkable(map, tx + dx, ty + dy)) return [tx + dx, ty + dy];
    }
  }
  return [tx, ty];
}

/** วางชาวเมืองประจำบนแผนที่ใกล้จุดสังเกตของตน (คงที่) */
export function placeCast(state, map) {
  const used = new Set();
  return visibleCast(state).map((c) => {
    let tx = c.fallback[0], ty = c.fallback[1];
    if (c.anchor != null) {
      const pts = [];
      for (let y = 0; y < map.h; y++) for (let x = 0; x < map.w; x++) if (map.tiles[y][x] === c.anchor) pts.push([x, y]);
      if (pts.length) { tx = Math.round(pts.reduce((a, p) => a + p[0], 0) / pts.length); ty = Math.max(...pts.map((p) => p[1])) + 1; }
    }
    let [x, y] = findNear(map, tx, ty);
    while (used.has(`${x},${y}`)) [x, y] = findNear(map, x + 1, y);
    used.add(`${x},${y}`);
    return { id: c.id, castId: c.id, name: c.name, identity: c.identity, x, y, color: c.color, isCast: true };
  });
}

export function castProgress(state, id) {
  const c = getCast(id);
  const cs = ensureCastState(state, id);
  return { done: cs.done.length, total: c.chapters.length, rel: cs.rel, available: Boolean(nextChapter(state, id)), label: getIdentity(c.identity).label };
}
